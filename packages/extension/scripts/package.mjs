// Packages the VSIX: production bundle + .NET host payload.
//   pnpm package:vsix                        fails when the host build output is missing
//   pnpm package:vsix -- --allow-missing-host   packages without host/ (the extension then reports HostNotFound)
// Host payload source: src/dotnet/Refyntra.Host/bin/Release/net10.0/** → packages/extension/host/
import { execFileSync } from 'node:child_process';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import fs from 'node:fs';
import path from 'node:path';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..');
const repo = path.resolve(root, '..', '..');
const allowMissingHost = process.argv.includes('--allow-missing-host');
const hostSource = process.env.REFYNTRA_HOST_BUILD_DIR || path.join(repo, 'src', 'dotnet', 'Refyntra.Host', 'bin', 'Release', 'net10.0');
const hostTarget = path.join(root, 'host');
const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
const outDir = path.join(repo, 'dist');
const outFile = path.join(outDir, `${pkg.name}-${pkg.version}.vsix`);

function fail(message) {
  console.error(`\npackage:vsix failed: ${message}`);
  process.exit(1);
}

// 1. Host payload.
fs.rmSync(hostTarget, { recursive: true, force: true });
const hostDll = path.join(hostSource, 'Refyntra.Host.dll');
if (fs.existsSync(hostDll)) {
  fs.cpSync(hostSource, hostTarget, { recursive: true });
  // Payload trimming (see scripts/package/audit.mjs):
  //  - BuildHost-net472 is only launched by Roslyn for .NET Framework / non-SDK-style projects, which the alpha does not support (docs/support/matrix.md).
  //  - .pdb files embed the build machine's absolute source paths.
  fs.rmSync(path.join(hostTarget, 'BuildHost-net472'), { recursive: true, force: true });
  for (const f of fs.readdirSync(hostTarget, { recursive: true })) if (f.endsWith('.pdb')) fs.rmSync(path.join(hostTarget, f), { force: true });
  const count = fs.readdirSync(hostTarget, { recursive: true }).length;
  console.log(`Host payload: copied ${count} entries from ${path.relative(repo, hostSource)}`);
} else if (allowMissingHost) {
  console.warn(`WARNING: host payload not found (${path.relative(repo, hostDll)}). Packaging WITHOUT the host because of --allow-missing-host; the installed extension will report HostNotFound.`);
} else {
  fail(`host payload not found: ${hostDll}\nBuild it first (pnpm build:host) or pass --allow-missing-host to package without it.`);
}

// 2. Production bundle.
execFileSync(process.execPath, [path.join(here, 'build.mjs'), '--production'], { stdio: 'inherit' });

// 3. vsce needs a LICENSE next to package.json; use the repository license (removed again afterwards).
const license = path.join(root, 'LICENSE');
const copiedLicense = !fs.existsSync(license);
if (copiedLicense) fs.copyFileSync(path.join(repo, 'LICENSE'), license);
// Third-party notices (generated by scripts/package/notices.mjs) ship in the VSIX together with packages/extension/legal/.
const notices = path.join(root, 'THIRD_PARTY_NOTICES.md');
fs.copyFileSync(path.join(repo, 'THIRD_PARTY_NOTICES.md'), notices);

try {
  fs.mkdirSync(outDir, { recursive: true });
  const require = createRequire(import.meta.url);
  const vsce = path.join(path.dirname(require.resolve('@vscode/vsce/package.json')), 'vsce');
  execFileSync(process.execPath, [vsce, 'package', '--no-dependencies', '--allow-missing-repository', '--out', outFile], { cwd: root, stdio: 'inherit' });
  execFileSync(process.execPath, [vsce, 'ls', '--no-dependencies'], { cwd: root, stdio: 'inherit' });
} catch (e) {
  fail(e instanceof Error ? e.message : String(e));
} finally {
  if (copiedLicense) fs.rmSync(license, { force: true });
  fs.rmSync(notices, { force: true });
}

const size = fs.statSync(outFile).size;
console.log(`\nVSIX: ${outFile} (${(size / 1024).toFixed(1)} KiB)${fs.existsSync(hostDll) ? '' : ' — WITHOUT host payload'}`);
