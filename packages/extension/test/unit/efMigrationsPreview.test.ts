import { describe, expect, it } from 'vitest';
import type { RefactorPlanDto } from '@refyntra/contracts';
import { validatePlanStructure } from '@refyntra/domain';
import { EF_NOT_BUILDING, EF_ONLY_LABEL, EF_UPDATE_LABEL, efMigrationItems, renamePreviewSummary } from '../../src/renameSummary';

// EF Core migrations in the rename preview (protocol 1.5): the choice between updating the migrations and renaming
// only the class, its own preview section, and the "will not build" warning.

const H = (c: string) => c.repeat(64);
const CTX = 'file:///ws/Api/Data/ShopDbContext.cs';
const DESIGNER = 'file:///ws/Api/Migrations/20250101000000_Initial.Designer.cs';
const SNAPSHOT = 'file:///ws/Api/Migrations/ShopDbContextModelSnapshot.cs';

function plan(mode: 'efMigrations' | 'none' | undefined): RefactorPlanDto {
  const text = (uri: string) => ({ kind: 'text' as const, uri, expectedHash: H('a'), resultHash: H('b'), edits: [] });
  return {
    planId: 'p',
    actionId: 'csharp.rename',
    providerRouteId: 'csharp.roslyn',
    protocolMajor: 1,
    workspaceId: 'ws',
    kind: 'owned-semantic',
    sessionEpoch: 'e',
    baseWorkspaceRevision: 0,
    baseSnapshotId: 's',
    projectContextIds: [],
    writeSet: mode === 'efMigrations' ? [text(CTX), text(DESIGNER), text(SNAPSHOT)] : [text(CTX)],
    readSet: [],
    evidence: [],
    limitations: mode === 'none' ? ['The project will not build until the migrations are updated: 20250101000000_Initial.Designer.cs, ShopDbContextModelSnapshot.cs still reference ShopDbContext (EF Core migrations were left unchanged as requested).'] : [],
    validation: { status: mode === 'none' ? 'limited' : 'valid', checkedContexts: [], uncheckedContexts: [], compilationDelta: mode === 'none' ? 'failed' : 'passed' },
    title: 'Rename ShopDbContext to StoreDbContext',
    ...(mode ? { efMigrations: { mode, files: [DESIGNER, SNAPSHOT] } } : {}),
  };
}

const files = (p: RefactorPlanDto) => p.writeSet.map((c) => ({ uri: (c as { uri: string }).uri, original: '', modified: '', editCount: 1 }));
const summary = (p: RefactorPlanDto) => renamePreviewSummary({ plan: p, state: 'Previewing', issues: [], applyEnabled: true }, files(p), false, (u) => u.replace('file:///ws/', ''));

describe('EF Core migrations in the rename preview', () => {
  it('(A) update the migrations: chosen option, own section with the files, strings not changed', () => {
    const p = plan('efMigrations');
    const items = efMigrationItems(p);
    expect(items.map((i) => i.label)).toEqual([`$(pass-filled) ${EF_UPDATE_LABEL}`, `$(circle-large-outline) ${EF_ONLY_LABEL}`]);
    expect(items.map((i) => i.action)).toEqual(['efInfo', 'efMode']);
    expect(items[1]?.mode).toBe('none');
    expect(items[1]?.description).toMatch(/new preview/);
    const s = summary(p);
    expect(s).toContain('## EF Core migrations (generated by EF)');
    expect(s).toContain(`Chosen: **${EF_UPDATE_LABEL}**`);
    expect(s).toContain('- Api/Migrations/ShopDbContextModelSnapshot.cs — 1 edit(s)');
    expect(s).toMatch(/Not changed: strings in migrations/);
    expect(s).toMatch(/next migration you add may contain changes/);
    // The migrations are listed in their own section, not among the other files.
    const filesSection = s.slice(s.indexOf('## Files'), s.indexOf('## EF Core migrations'));
    expect(filesSection).toContain('Api/Data/ShopDbContext.cs');
    expect(filesSection).not.toContain('Migrations');
    expect(s).not.toContain(EF_NOT_BUILDING);
    expect(validatePlanStructure(p)).toEqual([]);
  });

  it('(B) rename only the class: chosen option, warning at the top, migrations listed as unchanged, limited', () => {
    const p = plan('none');
    const items = efMigrationItems(p);
    expect(items.map((i) => i.label)).toEqual([`$(circle-large-outline) ${EF_UPDATE_LABEL}`, `$(pass-filled) ${EF_ONLY_LABEL}`]);
    expect(items.map((i) => i.action)).toEqual(['efMode', 'efInfo']);
    expect(items[0]?.mode).toBe('efMigrations');
    expect(items[1]?.description).toMatch(/will not build until the migrations are updated/);
    const s = summary(p);
    expect(s.split('\n').slice(0, 6).join('\n')).toContain(`**${EF_NOT_BUILDING}**`);
    expect(s).toContain('## Validation is limited');
    expect(s).toContain('- Api/Migrations/20250101000000_Initial.Designer.cs — unchanged');
    expect(s).toContain('Applying asks for an extra confirmation');
    expect(validatePlanStructure(p)).toEqual([]);
  });

  it('nothing for a plan without EF Core migrations', () => {
    const p = plan(undefined);
    expect(efMigrationItems(p)).toEqual([]);
    expect(summary(p)).not.toContain('EF Core migrations');
  });

  it('the domain validator refuses a "none" plan that edits a migration or claims to be valid', () => {
    const edits: RefactorPlanDto = { ...plan('none'), writeSet: plan('efMigrations').writeSet };
    expect(validatePlanStructure(edits).map((i) => i.message)).toContain('The plan edits an EF Core migration it says it leaves unchanged');
    const valid: RefactorPlanDto = { ...plan('none'), validation: { ...plan('none').validation, status: 'valid' } };
    expect(validatePlanStructure(valid).map((i) => i.message)).toContain('A rename that leaves EF Core migrations unchanged cannot be valid');
  });
});
