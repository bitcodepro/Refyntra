// ---- a small axe-like checker (no DOM library: the HTML is generated by us and well-formed) ----------------------------
interface Tag {
  name: string;
  attrs: Record<string, string>;
  closing: boolean;
  index: number;
}
function tags(html: string): Tag[] {
  const out: Tag[] = [];
  for (const m of html.matchAll(/<(\/?)([a-zA-Z][a-zA-Z0-9]*)((?:\s+[^\s=>/]+(?:="[^"]*")?)*)\s*\/?>/g)) {
    const attrs: Record<string, string> = {};
    for (const a of m[3]!.matchAll(/\s+([^\s=>/]+)(?:="([^"]*)")?/g)) attrs[a[1]!.toLowerCase()] = a[2] ?? '';
    out.push({ name: m[2]!.toLowerCase(), attrs, closing: m[1] === '/', index: m.index! });
  }
  return out;
}
/** Text content between a start tag and its matching end tag (no nested same-name tags in our buttons/summaries). */
function innerOf(html: string, openIndex: number, name: string): string {
  const start = html.indexOf('>', openIndex) + 1;
  return html.slice(start, html.indexOf(`</${name}>`, start));
}
const plain = (s: string) => s.replace(/<span[^>]*class="sr-only"[^>]*>.*?<\/span>/g, '').replace(/<span[^>]*aria-hidden="true"[^>]*>.*?<\/span>/g, '').replace(/<[^>]+>/g, '').replace(/&#\d+;/g, 'x').trim();

export function axeLikeViolations(html: string): string[] {
  const v: string[] = [];
  const all = tags(html);
  const open = all.filter((t) => !t.closing);
  // document basics
  if (!/^<!DOCTYPE html>/i.test(html)) v.push('doctype');
  if (!/<html lang="[a-z-]+"/.test(html)) v.push('html lang');
  if (!/<title>[^<]+<\/title>/.test(html)) v.push('title');
  if (open.filter((t) => t.name === 'main').length !== 1) v.push('exactly one <main>');
  // buttons: real buttons with an accessible name, type=button, no div/span pretending to be buttons
  for (const t of open.filter((x) => x.name === 'button')) {
    if (t.attrs.type !== 'button') v.push('button without type=button');
    if (!plain(innerOf(html, t.index, 'button'))) v.push(`button without an accessible name (${t.attrs['data-key']})`);
    if (t.attrs['aria-describedby'] && !html.includes(`id="${t.attrs['aria-describedby']}"`)) v.push(`aria-describedby target missing: ${t.attrs['aria-describedby']}`);
  }
  for (const t of open) {
    if (t.attrs.role === 'button' && t.name !== 'button') v.push(`<${t.name} role=button>`);
    if (t.attrs.onclick !== undefined || Object.keys(t.attrs).some((k) => /^on[a-z]+$/.test(k))) v.push(`inline event handler on <${t.name}>`);
    if ('style' in t.attrs) v.push(`inline style on <${t.name}>`);
    if (Object.values(t.attrs).some((val) => /^\s*javascript:/i.test(val))) v.push('javascript: url');
    if (t.name === 'img' && t.attrs.alt === undefined) v.push('img without alt');
    if (t.name === 'a' && !t.attrs.href) v.push('anchor without href');
    if (/^[1-9]/.test(t.attrs.tabindex ?? '')) v.push('positive tabindex');
  }
  // ids unique, references resolve
  const ids = open.map((t) => t.attrs.id).filter((x): x is string => !!x);
  for (const id of ids) if (ids.filter((x) => x === id).length > 1) v.push(`duplicate id ${id}`);
  for (const t of open) {
    for (const ref of [t.attrs['aria-labelledby'], t.attrs['aria-describedby']].filter((x): x is string => !!x)) for (const r of ref.split(/\s+/)) if (!ids.includes(r)) v.push(`dangling reference ${r}`);
  }
  // headings: one h1, no skipped levels, none empty
  const headings = open.filter((t) => /^h[1-6]$/.test(t.name));
  if (headings.filter((t) => t.name === 'h1').length !== 1) v.push('exactly one h1');
  let prev = 0;
  for (const t of headings) {
    const level = Number(t.name[1]);
    if (prev && level > prev + 1) v.push(`heading level skipped: h${prev} -> h${level}`);
    if (!plain(innerOf(html, t.index, t.name))) v.push('empty heading');
    prev = level;
  }
  // disclosure widgets: <details> starts with <summary> that has text
  for (const t of open.filter((x) => x.name === 'details')) {
    const after = html.slice(html.indexOf('>', t.index) + 1);
    if (!after.startsWith('<summary')) v.push('details without a leading summary');
  }
  for (const t of open.filter((x) => x.name === 'summary')) if (!plain(innerOf(html, t.index, 'summary'))) v.push('empty summary');
  // sections are labelled; scrollable regions are focusable and named; tables have headers
  for (const t of open.filter((x) => x.name === 'section')) if (!t.attrs['aria-labelledby'] && !t.attrs['aria-label']) v.push('unlabelled section');
  for (const t of open.filter((x) => x.attrs.class?.split(/\s+/).includes('table-wrap'))) if (t.attrs.tabindex !== '0' || !t.attrs['aria-label'] || t.attrs.role !== 'region') v.push('scrollable region not focusable/named');
  for (const t of open.filter((x) => x.name === 'table')) {
    const rest = html.slice(t.index, html.indexOf('</table>', t.index));
    if (!/<th[ >]/.test(rest)) v.push('table without header cells');
    if (!/<caption/.test(rest)) v.push('table without caption');
  }
  // live region: persistent, outside <main>, polite
  const live = open.find((t) => t.attrs.id === 'live');
  if (!live || live.attrs.role !== 'status' || live.attrs['aria-live'] !== 'polite') v.push('polite live region #live');
  if (live && html.indexOf('id="live"') > html.indexOf('<main')) v.push('live region must come before/outside main so it survives innerHTML updates');
  // emoji / status glyphs: only inside aria-hidden spans, never the only carrier of meaning
  const withoutHidden = html.replace(/<span[^>]*aria-hidden="true"[^>]*>.*?<\/span>/g, '');
  const body = withoutHidden.slice(withoutHidden.indexOf('<body'));
  for (const g of Object.values(ICON_GLYPH)) if (body.includes(g)) v.push(`glyph ${g} outside aria-hidden`);
  for (const m of html.matchAll(/<span class="icon[^"]*" aria-hidden="true">(?:<svg[^]*?<\/svg>|[^<]*)<\/span>(.{0,120})/g)) if (!plain(m[1]!.replace(/<\/?(?:button|div|h2)[^>]*>/g, ' ')).length) v.push('icon without adjacent text');
  // CSP: no inline script/style without nonce, no unsafe-inline
  if (/unsafe-inline|unsafe-eval/.test(html)) v.push('unsafe CSP');
  if (/<script(?![^>]*nonce=)/.test(html) || /<style(?![^>]*nonce=)/.test(html)) v.push('script/style without nonce');
  return v;
}

