describe('keyboard reachability of commands (package.json + status bar menu)', () => {
  const pkg = JSON.parse(readFileSync(resolve(__dirname, '../../package.json'), 'utf8')) as {
    contributes: { commands: Array<{ command: string; title: string; category?: string }>; menus: { commandPalette: Array<{ command: string; when?: string }> }; keybindings: Array<{ command: string; key: string; when: string }> };
  };
  const INTERNAL = ['refyntra.openLocation', 'refyntra.openMetadata', 'refyntra.runRestore', 'refyntra.related.open', 'refyntra.nativeRename', 'refyntra.stackTrace.openFrame', 'refyntra.stackTrace.related', 'refyntra.taskContext.addFindItem', 'refyntra.taskContext.addFromRelated', 'refyntra.codeLens.related', 'refyntra.selectRunTargetById', 'refyntra.pickDotnetProcess', 'refyntra.immediate.clear', 'refyntra.editAction', 'refyntra.usages.open', 'refyntra.usages.activate', 'refyntra.usages.closeSession', 'refyntra.usages.showMore', 'refyntra.tests.run', 'refyntra.tests.debug', 'refyntra.ef.open', ...['kind', 'project', 'folder', 'file', 'type', 'member'].flatMap((g) => [`refyntra.usages.group.${g}`, `refyntra.usages.ungroup.${g}`])];

  it('only internal commands are hidden from the Command Palette; every command has a title and the Refyntra category', () => {
    const hidden = pkg.contributes.menus.commandPalette.filter((m) => m.when === 'false').map((m) => m.command);
    expect(hidden.sort()).toEqual([...INTERNAL].sort());
    for (const c of pkg.contributes.commands) {
      expect(c.title.length, c.command).toBeGreaterThan(2);
      expect(c.category, c.command).toBe('Refyntra');
    }
  });

  it('every user command is in the status bar menu, or is a Related view toolbar command that the palette offers', () => {
    const inMenu = new Set(MAIN_MENU.map((m) => m.command));
    const viewToolbar = new Set(['refyntra.showMenu', 'refyntra.statusMenu', 'refyntra.related.pin', 'refyntra.related.unpin', 'refyntra.related.refresh', 'refyntra.stackTrace.clear', 'refyntra.stop', 'refyntra.restart', 'refyntra.run.refresh']);
    for (const c of pkg.contributes.commands.map((x) => x.command)) {
      if (INTERNAL.includes(c) || viewToolbar.has(c)) continue;
      // Task Context view: title-bar and item commands, all in the palette; the menu leads to the view (Switch).
      if (c.startsWith('refyntra.taskContext.') && inMenu.has('refyntra.taskContext.switch')) continue;
      // EF Core view (shown when the workspace has a DbContext): title-bar and item commands, all in the palette.
      if (c.startsWith('refyntra.ef.')) continue;
      // Usages view: title-bar commands, all in the palette; the menu leads to the view (Find Usages).
      if (c.startsWith('refyntra.usages.') && inMenu.has('refyntra.findUsages')) continue;
      expect(inMenu.has(c), `${c} is missing from the status bar menu (MAIN_MENU)`).toBe(true);
    }
  });

  it('status bar menu labels read without the icon (text follows the codicon)', () => {
    for (const m of MAIN_MENU) expect(m.label.replace(/^\$\([a-z-]+\)\s*/, '').length).toBeGreaterThan(3);
  });

  it('keybinding presets (every binding is gated by the preset setting)', () => {
    for (const k of pkg.contributes.keybindings) expect(k.when).toMatch(/config\.refyntra\.keybindings\.preset == '(visualStudio|resharper)'/);
  });
});
