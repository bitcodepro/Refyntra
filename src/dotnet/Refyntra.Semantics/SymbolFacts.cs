using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace Refyntra.Semantics;

public static class SymbolFacts
{
    public static readonly SymbolDisplayFormat DisplayFormat = SymbolDisplayFormat.CSharpErrorMessageFormat;

    public static Project? OwningProject(Solution solution, ISymbol symbol)
    {
        var tree = symbol.Locations.FirstOrDefault(l => l.IsInSource)?.SourceTree;
        if (tree == null) return null;
        return solution.GetDocument(tree)?.Project;
    }

    public static string Kind(ISymbol symbol) => symbol switch
    {
        INamespaceSymbol => "namespace",
        INamedTypeSymbol t => t.TypeKind switch
        {
            TypeKind.Interface => "interface",
            TypeKind.Enum => "enum",
            TypeKind.Delegate => "delegate",
            TypeKind.Struct => t.IsRecord ? "record" : "struct",
            TypeKind.Class => t.IsRecord ? "record" : "class",
            _ => "other",
        },
        IMethodSymbol m => m.MethodKind is MethodKind.Constructor or MethodKind.StaticConstructor ? "constructor" : "method",
        IPropertySymbol => "property",
        IFieldSymbol => "field",
        IEventSymbol => "event",
        IParameterSymbol => "parameter",
        ILocalSymbol => "local",
        _ => "other",
    };

    public static string Name(ISymbol symbol) =>
        symbol is IMethodSymbol { MethodKind: MethodKind.Constructor or MethodKind.StaticConstructor } m ? m.ContainingType.Name : symbol.Name;

    public static string DisplayName(ISymbol symbol) => symbol.ToDisplayString(DisplayFormat);

    public static string? ContainerName(ISymbol symbol)
    {
        if (symbol.ContainingType != null) return symbol.ContainingType.ToDisplayString(DisplayFormat);
        if (symbol.ContainingNamespace is { IsGlobalNamespace: false } ns) return ns.ToDisplayString();
        return null;
    }

    /// <summary>True for files that are produced by tools: obj/ outputs, *.g.cs, *.designer.cs, auto-generated headers, source generators.</summary>
    public static bool IsGeneratedPath(string? path)
    {
        if (string.IsNullOrEmpty(path)) return true;
        var p = path.Replace('\\', '/');
        var file = Path.GetFileName(p);
        if (p.Contains("/obj/", StringComparison.OrdinalIgnoreCase)) return true;
        return file.EndsWith(".g.cs", StringComparison.OrdinalIgnoreCase) || file.EndsWith(".g.i.cs", StringComparison.OrdinalIgnoreCase)
            || file.EndsWith(".designer.cs", StringComparison.OrdinalIgnoreCase) || file.EndsWith(".generated.cs", StringComparison.OrdinalIgnoreCase)
            || file.StartsWith("TemporaryGeneratedFile_", StringComparison.OrdinalIgnoreCase);
    }

    public static bool IsGeneratedTree(Solution solution, SyntaxTree tree, CancellationToken ct)
    {
        var doc = solution.GetDocument(tree);
        if (doc == null || doc is SourceGeneratedDocument) return true;
        if (IsGeneratedPath(tree.FilePath)) return true;
        var root = tree.GetRoot(ct);
        var leading = root.GetLeadingTrivia().ToFullString();
        return leading.Contains("<auto-generated", StringComparison.OrdinalIgnoreCase);
    }

    public static string Origin(Solution solution, ISymbol symbol, CancellationToken ct)
    {
        var loc = symbol.Locations.FirstOrDefault(l => l.IsInSource);
        if (loc == null) return "metadata";
        return IsGeneratedTree(solution, loc.SourceTree!, ct) ? "generated" : "source";
    }

    public static Location? PrimaryLocation(ISymbol symbol) => symbol.Locations.FirstOrDefault(l => l.IsInSource);

    public static string? Preview(Location location)
    {
        var tree = location.SourceTree;
        if (tree == null || !tree.TryGetText(out var text)) text = tree?.GetText();
        if (text == null) return null;
        var line = text.Lines.GetLineFromPosition(location.SourceSpan.Start);
        var s = line.ToString().Trim();
        return s.Length > 200 ? s.Substring(0, 200) : s;
    }

    public static int ToOffset(SourceText text, int line, int character)
    {
        if (line < 0 || character < 0) throw new ArgumentOutOfRangeException(nameof(line));
        if (line >= text.Lines.Count) line = text.Lines.Count - 1;
        var l = text.Lines[line];
        return Math.Min(l.Start + character, l.End);
    }
}
